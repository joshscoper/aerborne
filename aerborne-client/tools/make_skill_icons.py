def draw(rows):
    img = Image.new("RGBA", (len(rows[0]), len(rows)), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        assert len(row) == img.width, (row, len(row))
        for x, ch in enumerate(row):
            if ch != ".":
                px[x, y] = P[ch] + (255,)
    return img


def main(assets):
    root = pathlib.Path(assets) / "textures" / "gui" / "sprites" / "ui"
    for name, rows in ICONS.items():
        out = root / "skills" / (name + ".png")
        out.parent.mkdir(parents=True, exist_ok=True)
        draw(rows).save(out)
    for name, rows in SMALL.items():
        out = root / "hud" / (name + ".png")
        out.parent.mkdir(parents=True, exist_ok=True)
        draw(rows).save(out)
    print("drew", len(ICONS), "icons and", len(SMALL), "HUD icons")


if __name__ == "__main__":
    main(sys.argv[1])
