# Grey per row, light at the top: the text colour multiplies it, so letters look lit from above.
SHADE = [255, 251, 245, 238, 230, 220, 208, 196, 184]
ROWS = 9
CELL = 12


def small_caps(glyph):
    """Lower case: the capital with its second and seventh rows taken out, seven rows tall on the baseline."""
    rows = [row for i, row in enumerate(glyph) if i not in (1, 6)]
    width = len(glyph[0])
    return ["." * width] * 2 + rows


def main(assets):
    assets = pathlib.Path(assets)
    glyphs = {}
    glyphs.update(CAPS)
    for c, g in CAPS.items():
        glyphs[c.lower()] = small_caps(g)
    glyphs.update(FIGURES)
    glyphs.update(MARKS)
    order = list(glyphs)
    per_row = 16
    rows = (len(order) + per_row - 1) // per_row
    sheet = Image.new("RGBA", (per_row * CELL, rows * CELL), (0, 0, 0, 0))
    px = sheet.load()
    lines = []
    for index, char in enumerate(order):
        gx, gy = (index % per_row) * CELL, (index // per_row) * CELL
        for y, row in enumerate(glyphs[char]):
            for x, cell in enumerate(row):
                if cell == "#":
                    shade = SHADE[y]
                    px[gx + x, gy + y + (CELL - ROWS - 1)] = (shade, shade, shade, 255)
        if index % per_row == 0:
            lines.append("")
        lines[-1] += char
    # Pad the last line of the character table to a full row.
    lines[-1] += "\u0000" * (per_row - len(lines[-1]))
    (assets / "textures" / "font").mkdir(parents=True, exist_ok=True)
    sheet.save(assets / "textures" / "font" / "heading.png")
    font = {"providers": [
        {"type": "space", "advances": {" ": 4}},
        {"type": "bitmap", "file": "aerborne_client:font/heading.png", "height": CELL, "ascent": CELL - 3, "chars": lines},
    ]}
    (assets / "font").mkdir(parents=True, exist_ok=True)
    (assets / "font" / "heading.json").write_text(json.dumps(font, indent=2, ensure_ascii=True) + chr(10), encoding="utf-8")
    print("wrote", len(order), "glyphs")


if __name__ == "__main__":
    main(sys.argv[1])
