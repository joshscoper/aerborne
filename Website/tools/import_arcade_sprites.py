"""Copy supplied WebP sprites unchanged and measure their visible bounds for canvas rendering.

Usage: python tools/import_arcade_sprites.py PATH_TO_COMPLETE_SPRITE_PACK.zip
Pillow is needed only for this import step, not by the running arcade.
"""
import io
import json
from pathlib import Path
import re
import sys
import zipfile

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PACKS = {"sky-hop": "SkyHop", "gem-rush": "GemRush", "cloud-catch": "CloudCatch",
         "codex-memory": "CodexMemory", "forge-strike": "ForgeStrike", "rune-breaker": "RuneBreaker"}


def main(archive):
    catalog = {}
    total = 0
    with zipfile.ZipFile(archive) as bundle:
        for slug, name in PACKS.items():
            prefix = "Aerborne_Arcade_Sprite_Packs_v1/Aerborne_%s_Sprite_Pack/" % name
            manifest = json.loads(bundle.read(prefix + "manifest.json").decode("utf-8-sig"))
            assets = {}
            destination = ROOT / "aerborne/static/img/arcade/sprites" / slug
            destination.mkdir(parents=True, exist_ok=True)
            for asset in manifest["assets"]:
                identifier = asset["id"]
                if not re.fullmatch(r"[a-z0-9_]+", identifier):
                    raise ValueError("Invalid sprite identifier")
                # Use large sources where the object occupies a significant part of the field.
                large = (slug == "forge-strike" and identifier.startswith(("hammer_", "anvil_"))) or (
                    slug == "sky-hop" and identifier.startswith("island_")) or (
                    slug == "codex-memory" and identifier.startswith("card_"))
                resolution = 512 if large else 256
                image = Image.open(io.BytesIO(bundle.read(prefix + "png/512/" + identifier + ".png")))
                alpha = image.getchannel("A")
                box = alpha.point(lambda a: 255 if a >= 12 else 0).getbbox()
                if box is None:
                    raise ValueError("Empty sprite: " + identifier)
                x1, y1, x2, y2 = box
                x1, y1, x2, y2 = max(0, x1-4), max(0, y1-4), min(512, x2+4), min(512, y2+4)
                relative = "arcade/sprites/%s/%s.webp" % (slug, identifier)
                (destination / (identifier + ".webp")).write_bytes(
                    bundle.read(prefix + "webp/%d/" % resolution + identifier + ".webp"))
                assets[identifier] = {"file": relative, "box": [x1, y1, x2-x1, y2-y1]}
                total += 1
            catalog[slug] = assets
    target = ROOT / "aerborne/static/js/arcade/assets.js"
    target.write_text("// Supplied sprite files and measured alpha bounds; generated by tools/import_arcade_sprites.py.\n"
                      "window.ArcadeSpriteCatalog = " + json.dumps(catalog, indent=2, sort_keys=True) + ";\n", encoding="utf-8")
    print("Imported %d sprites for %d games (source WebP files preserved)." % (total, len(catalog)))


if __name__ == "__main__":
    main(sys.argv[1])
